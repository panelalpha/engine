<div class="steps">
    <span class="steps-title">How to get the token</span>
    <ol>
        <li><span class="n">1.</span><span>Go to <a href="https://gitlab.com/-/user_settings/personal_access_tokens" target="_blank" rel="noopener">GitLab → Preferences → Access tokens</a>.</span></li>
