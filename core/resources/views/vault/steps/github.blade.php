<div class="steps">
    <span class="steps-title">How to get the token</span>
    <ol>
        <li><span class="n">1.</span><span>Go to <a href="https://github.com/settings/personal-access-tokens/new" target="_blank" rel="noopener">GitHub → Settings → Developer settings → Personal access tokens</a>.</span></li>
        <li><span class="n">2.</span><span>Click <strong>Generate new token</strong> and give it a name.</span></li>
        <li><span class="n">3.</span><span>Under <strong>Repository access</strong> choose <strong>Only select repositories</strong> and pick the repository to deploy.</span></li>
        <li><span class="n">4.</span><span>Under <strong>Permissions</strong> set:
            <ul>
                <li><span class="dash">–</span><span><strong>Contents</strong> → Read-only</span></li>
            </ul>
        </span></li>
        <li><span class="n">5.</span><span>Click <strong>Generate token</strong>.</span></li>
    </ol>
</div>
